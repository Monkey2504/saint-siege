// Embed the Newsreader serif the way the other two faces are embedded.
//
// The game ships offline and behind corporate blockers: a face fetched from
// fonts.googleapis.com at runtime fails silently and takes the direction with
// it (src/fonts.css says so at the top, and it is the reason that file is
// generated rather than linked). The design proposal sets every letter and
// every written analysis in Newsreader, so it has to live in public/fonts like
// Archivo and Bricolage Grotesque.
//
// Latin and latin-ext only: the interface has no Vietnamese, and the two ranges
// the game actually renders are the two the other faces ship.

import fs from "node:fs";
import path from "node:path";

const OUT_DIR = path.resolve("public/fonts");
const CSS_OUT = path.resolve("src/fonts.css");
const KEEP = ["latin", "latin-ext"];

const API = "https://fonts.googleapis.com/css2?family=Newsreader:ital,wght@0,400;0,600;0,700;1,400&display=swap";
const UA = "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0 Safari/537.36";

const sheet = await fetch(API, { headers: { "User-Agent": UA } }).then((r) => r.text());

// Each @font-face is preceded by a /* subset */ comment naming its range.
const faces = [];
const re = /\/\* ([a-z-]+) \*\/\s*@font-face \{([^}]*)\}/g;
for (const m of sheet.matchAll(re)) {
  const [, subset, body] = m;
  if (!KEEP.includes(subset)) continue;
  const style = body.match(/font-style:\s*([^;]+);/)[1].trim();
  const weight = body.match(/font-weight:\s*([^;]+);/)[1].trim();
  const url = body.match(/url\(([^)]+)\)/)[1].trim();
  const range = body.match(/unicode-range:\s*([^;]+);/)[1].trim();
  faces.push({ subset, style, weight, url, range });
}

if (!faces.length) throw new Error("no faces parsed — Google's sheet format changed");

const lines = [];
for (const [i, face] of faces.entries()) {
  const name = `newsreader-${face.weight}-${face.style}-${face.subset}-${i}.woff2`;
  const bytes = Buffer.from(await fetch(face.url, { headers: { "User-Agent": UA } }).then((r) => r.arrayBuffer()));
  fs.writeFileSync(path.join(OUT_DIR, name), bytes);
  lines.push(
    `@font-face {`,
    `  font-family: "Newsreader";`,
    `  font-style: ${face.style};`,
    `  font-weight: ${face.weight};`,
    `  font-display: swap;`,
    `  src: url("/fonts/${name}") format("woff2");`,
    `  unicode-range: ${face.range};`,
    `}`,
    ``,
  );
  console.log(`${name} — ${(bytes.length / 1024).toFixed(1)} kB`);
}

// Appended, never rewritten: the existing faces were generated by a tool that
// is no longer in the repository, and re-deriving them here would risk losing
// the two families the whole interface is set in.
const existing = fs.readFileSync(CSS_OUT, "utf8");
if (existing.includes('font-family: "Newsreader"')) {
  console.log("fonts.css already carries Newsreader — not appended twice.");
} else {
  fs.writeFileSync(CSS_OUT, `${existing.trimEnd()}\n\n${lines.join("\n")}`);
  console.log(`appended ${faces.length} faces to src/fonts.css`);
}
