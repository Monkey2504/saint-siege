// Extracts the world's country names ONCE, from the countries tile archive, into
// a small JSON file the game can ship.
//
// Why: the list of polities is read at runtime out of tile zero of
// countries.pmtiles (src/runtime/assets.js loadCountryNames). That is a 62 MB
// download, and it is the reason a player must fetch 289 MB of cartography
// before the first turn — in a game whose Holy See scenario owns one enclave of
// half a square kilometre, has no units and never moves a frontier. The map is
// an atlas the player never opens, and the only thing the engine truly needs
// from it is the names.
//
// Ten modules depend on that list: correspondence, naturalisation, the chat
// invitee resolver, the translator, the cheats, the library bar. So the list has
// to survive the map's removal, and this is how.
//
// Run once, against an installation that already has the tiles:
//   node scripts/extract-country-names.mjs
import fs from "node:fs";
import path from "node:path";
import { PMTiles } from "pmtiles";
import { VectorTile } from "@mapbox/vector-tile";
import Pbf from "pbf";

const TILES = process.env.OH_TILES
  || path.join(process.env.APPDATA ?? "", "open-historia", "public", "assets", "countries.pmtiles");
const OUT = path.join(process.cwd(), "src", "runtime", "countryNames.js");

// A file-backed source, because the pmtiles library ships a fetch-based one for
// the browser and this runs in Node against a file on disk.
class FileSource {
  constructor(file) {
    this.file = file;
    this.handle = fs.openSync(file, "r");
  }
  getKey() { return this.file; }
  async getBytes(offset, length) {
    const buffer = Buffer.alloc(length);
    fs.readSync(this.handle, buffer, 0, length, offset);
    return { data: buffer.buffer.slice(buffer.byteOffset, buffer.byteOffset + length) };
  }
}

if (!fs.existsSync(TILES)) {
  console.error(`No tile archive at ${TILES}.`);
  console.error("Point OH_TILES at a countries.pmtiles from an installation that has downloaded the map.");
  process.exit(1);
}

const archive = new PMTiles(new FileSource(TILES));
const tile = await archive.getZxy(0, 0, 0);
if (!tile?.data) {
  console.error("Tile 0/0/0 is empty — this archive does not carry the overview tile.");
  process.exit(1);
}

const layer = new VectorTile(new Pbf(new Uint8Array(tile.data))).layers.countries;
if (!layer) {
  console.error("The archive has no 'countries' layer.");
  process.exit(1);
}

// The same field precedence assets.js uses, so the shipped list and the tiles
// can never disagree about a name.
const seen = new Map();
for (let i = 0; i < layer.length; i += 1) {
  const p = layer.feature(i).properties ?? {};
  const code = String(p.GID_0 ?? p.gid_0 ?? p.ISO_A3 ?? p.iso_a3 ?? "").trim();
  const name = String(p.Country ?? p.NAME ?? p.name ?? p.COUNTRY ?? "").trim();
  if (!name) continue;
  const key = name.toLowerCase();
  if (!seen.has(key)) seen.set(key, { code, name });
}

const countries = [...seen.values()].sort((a, b) => a.name.localeCompare(b.name));
// A module rather than a .json file: Node ESM needs an import attribute for
// JSON, and without it the test runner fails to load every module that touches
// it — which took the whole suite down from 548 tests to 516 the first time.
// A plain export works in the bundler, in Node and in the browser alike.
const banner = [
  "/*! Open Historia — the world's country names, extracted once from the tiles © 2026 Nicholas Krol, MIT (see src/Editor/LICENSE). */",
  "// Generated by scripts/extract-country-names.mjs — do not edit by hand.",
  "// It exists so the game can name every polity without downloading 62 MB of",
  "// geometry it never draws. Regenerate it if the tile archive changes.",
  "",
].join("\n");
fs.writeFileSync(OUT, `${banner}export default ${JSON.stringify(countries, null, 0)};\n`);

const bytes = fs.statSync(OUT).size;
console.log(`${countries.length} countries -> ${path.relative(process.cwd(), OUT)} (${(bytes / 1024).toFixed(1)} kB)`);
console.log(`replacing a ${(fs.statSync(TILES).size / 1e6).toFixed(1)} MB download`);
